const dicts: Record<Locale, Record<Key, string>> = { zh, en }

export type Args = Record<string, string | number | undefined>
export type T = (key: string, args?: Args) => string

export function translate(locale: Locale, key: string, args?: Args): string {
  const s = dicts[locale][key as Key] ?? key
  return args ? s.replace(/\{(\w+)\}/g, (_, k) => String(args[k] ?? '')) : s
}

/** Stable per locale, so it is safe in effect and callback dependencies. */
export function useT(): T {
  const locale = useStore((s) => s.locale)
  return useCallback((key: string, args?: Args) => translate(locale, key, args), [locale])
}
